// Turns docs/rwa-registry.json (from scripts/discover-rwa.mjs) into the typed list the app ships:
//   packages/shared/src/token-registry.data.ts
// Offline, sends nothing. From the repo root:  node scripts/build-token-registry.mjs
// Re-run after every discover-rwa run and commit both files.
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "docs/rwa-registry.json";
const OUT = "packages/shared/src/token-registry.data.ts";
const MAX_IMPACT_PCT = 0.5; // anything with more price impact on a 1 USDT quote is not offered
const ROUTER = "0xB44446b0c8E56988c34f7Ff73Ae904982b5FdDA5".toLowerCase(); // approve target every verified quote uses

// README: no perps / leverage products. Match on the issuer's company name.
const LEVERAGED = /\b[2-9]x\b|ultrapro|ultra\b|\bbull\b|\bbear\b|inverse|\bshort\b|\blong\b|leverag/i;

const reg = JSON.parse(readFileSync(SRC, "utf8"));
if (reg.chain !== 56 && reg.chain !== "56") throw new Error(`registry is for chain ${reg.chain}, expected 56`);

const kept = [];
const dropped = [];
for (const t of reg.tokens) {
  const why = (() => {
    if (t.platform !== "bstock") return "not a bStock (Ondo needs a $5+ RFQ flow the app does not support)";
    if (!t.quote) return `no quote: ${t.quoteError ?? "unknown"}`;
    const q = t.quote;
    if (q.executionMode !== "SWAP") return `execution mode ${q.executionMode}`;
    if (q.honeyPot) return "honeypot flag";
    if (Number(q.taxRate) !== 0) return `token tax ${q.taxRate}`;
    if (Number(q.decimals) !== 18) return `decimals ${q.decimals} (app assumes 18 for display math)`;
    if (String(q.approveTarget).toLowerCase() !== ROUTER) return `unexpected approve target ${q.approveTarget}`;
    if (Number(q.priceImpactPercent) > MAX_IMPACT_PCT) return `price impact ${q.priceImpactPercent}%`;
    if (LEVERAGED.test(t.company ?? "")) return `leveraged/inverse product: ${t.company}`;
    if (!/^0x[0-9a-fA-F]{40}$/.test(t.address)) return "bad address";
    return null;
  })();
  if (why) dropped.push({ symbol: t.symbol, why });
  else kept.push(t);
}

const seen = new Set();
for (const t of kept) {
  const a = t.address.toLowerCase();
  if (seen.has(a) || seen.has(t.symbol)) throw new Error(`duplicate ${t.symbol} ${a}`);
  seen.add(a); seen.add(t.symbol);
}
kept.sort((a, b) => a.symbol.localeCompare(b.symbol));

const rows = kept.map((t) =>
  `  { symbol: ${JSON.stringify(t.symbol)}, ticker: ${JSON.stringify(t.ticker)}, name: ${JSON.stringify(t.company)}, address: ${JSON.stringify(t.address.toLowerCase())}, decimals: 18, priceImpactPct: ${Number(t.quote.priceImpactPercent)} },`,
);

writeFileSync(
  OUT,
  `// GENERATED by scripts/build-token-registry.mjs from docs/rwa-registry.json (${reg.generatedAt}). Do not edit by hand.
// bStocks on BSC that quoted as a normal SWAP with no honeypot/tax flag, low price impact and no leverage.
// Being listed here does NOT make a token tradable: see VERIFIED_LIVE_SYMBOLS in token-registry.ts.

export interface RegistryRow {
  symbol: string;
  ticker: string;
  name: string;
  /** Lowercase. Comes from Binance RWA search, never guessed. */
  address: string;
  decimals: 18;
  /** Price impact of a 1 USDT quote when the registry was generated. */
  priceImpactPct: number;
}

export const REGISTRY_GENERATED_AT = ${JSON.stringify(reg.generatedAt)};

export const REGISTRY_ROWS: readonly RegistryRow[] = [
${rows.join("\n")}
];
`,
);

const byWhy = {};
for (const d of dropped) (byWhy[d.why.split(":")[0].replace(/[\d.]+%?/g, "#")] ??= []).push(d.symbol);
console.log(`kept ${kept.length} of ${reg.tokens.length}; wrote ${OUT}`);
for (const [why, syms] of Object.entries(byWhy)) console.log(`  dropped ${syms.length}: ${why}${syms.length <= 8 ? " (" + syms.join(", ") + ")" : ""}`);
