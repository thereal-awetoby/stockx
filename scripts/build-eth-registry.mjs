// Turns docs/eth-dex-routes.json (from scripts/eth-dex-scan.mjs) into packages/shared/src/eth-registry.data.ts.
// Run from the repo root:  node scripts/build-eth-registry.mjs
import fs from "node:fs";

const src = new URL("../docs/eth-dex-routes.json", import.meta.url);
const out = new URL("../packages/shared/src/eth-registry.data.ts", import.meta.url);
const scan = JSON.parse(fs.readFileSync(src, "utf8"));
const rows = scan.tokens
  .filter((t) => t.routable)
  .map((t) => ({ symbol: t.symbol, name: t.name ?? null, address: String(t.address).toLowerCase(), lossPct: t.lossPct ?? null, gasUsd: t.gasUsd ?? null }))
  .sort((a, b) => a.symbol.localeCompare(b.symbol));

const body = `// GENERATED by scripts/build-eth-registry.mjs from docs/eth-dex-routes.json. Do not edit by hand.
export interface EthRow { symbol: string; name: string | null; address: string; lossPct: number | null; gasUsd: number | null }
export const ETH_ROWS: EthRow[] = ${JSON.stringify(rows, null, 1)};
`;
fs.writeFileSync(out, body);
const clean = rows.filter((r) => r.lossPct !== null && r.lossPct < 2);
console.log(`Wrote ${rows.length} tokens with a route (${clean.length} clean, under 2% loss at $${scan.amountUsd}).`);
console.log("Tradable:", clean.map((r) => r.symbol).join(", "));
